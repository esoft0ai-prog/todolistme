/**
 * Minimal, dependency-free SHA-256 / HMAC-SHA256 / PBKDF2 implementation.
 * Used for PIN hashing (with a random salt, stored in the Android Keystore)
 * and backup checksums. Verified against RFC/NIST test vectors in tests.
 */

